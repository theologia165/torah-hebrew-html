-- DTWorks 2 / PostgreSQL proof-of-concept schema
-- Target: PostgreSQL 15+
-- Purpose: reproduce the 050 Notion search UI with SQL while preserving
-- MorphHB source detail for later scholarly searches.

BEGIN;

CREATE SCHEMA IF NOT EXISTS dtworks;

CREATE TABLE IF NOT EXISTS dtworks.source_versions (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_name     TEXT NOT NULL,
    source_commit   TEXT NOT NULL,
    source_license  TEXT,
    imported_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes           TEXT,
    UNIQUE (source_name, source_commit)
);

CREATE TABLE IF NOT EXISTS dtworks.books (
    id              SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    osis_code       TEXT NOT NULL UNIQUE,
    english_name    TEXT NOT NULL,
    japanese_name   TEXT NOT NULL,
    tanakh_group    TEXT NOT NULL CHECK (tanakh_group IN ('torah','former','latter','writings')),
    canonical_order SMALLINT NOT NULL UNIQUE
);

-- WLC and KJV-style numbering can differ. Keep both explicitly rather than
-- silently renumbering verses. The source OSIS id is the WLC reference.
CREATE TABLE IF NOT EXISTS dtworks.verses (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_version_id BIGINT NOT NULL REFERENCES dtworks.source_versions(id) ON DELETE RESTRICT,
    book_id         SMALLINT NOT NULL REFERENCES dtworks.books(id) ON DELETE RESTRICT,
    chapter_wlc     SMALLINT NOT NULL CHECK (chapter_wlc > 0),
    verse_wlc       SMALLINT NOT NULL CHECK (verse_wlc > 0),
    osis_wlc        TEXT NOT NULL,
    chapter_kjv     SMALLINT,
    verse_kjv       SMALLINT,
    osis_kjv        TEXT,
    UNIQUE (source_version_id, book_id, chapter_wlc, verse_wlc),
    UNIQUE (source_version_id, osis_wlc)
);

-- One row per orthographic <w> token in MorphHB.
-- Common search fields are denormalized here for fast UI queries.
CREATE TABLE IF NOT EXISTS dtworks.tokens (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    verse_id            BIGINT NOT NULL REFERENCES dtworks.verses(id) ON DELETE CASCADE,
    token_index         SMALLINT NOT NULL CHECK (token_index > 0),

    surface             TEXT NOT NULL,
    -- Hebrew form with cantillation/meteg removed but niqqud retained.
    -- Generated by the importer, not by SQL, to keep Unicode handling explicit.
    form_search         TEXT NOT NULL,
    -- Consonantal form for a possible later "ignore vowels" search.
    form_consonantal    TEXT NOT NULL,

    lemma_raw           TEXT NOT NULL,
    primary_strong      INTEGER,
    lemma_display       TEXT,

    morph_raw           TEXT NOT NULL,
    language_code       CHAR(1) NOT NULL CHECK (language_code IN ('H','A')),
    main_pos_code       CHAR(1),
    main_stem_code      CHAR(1),
    main_conjugation_code CHAR(1),
    person_code         CHAR(1),
    gender_code         CHAR(1),
    number_code         CHAR(1),
    state_code          CHAR(1),

    UNIQUE (verse_id, token_index)
);

-- A MorphHB lemma attribute can contain multiple slash-delimited components.
-- Preserve every numeric lexeme component instead of keeping only the first.
CREATE TABLE IF NOT EXISTS dtworks.token_lemmas (
    token_id        BIGINT NOT NULL REFERENCES dtworks.tokens(id) ON DELETE CASCADE,
    lemma_index     SMALLINT NOT NULL CHECK (lemma_index > 0),
    raw_component   TEXT NOT NULL,
    strong_number   INTEGER,
    is_primary      BOOLEAN NOT NULL DEFAULT false,
    PRIMARY KEY (token_id, lemma_index)
);

-- Preserve each slash-delimited MorphHB morphology segment.
-- The tokens table contains the main searchable analysis; this table retains
-- prefixes, the lexical core and suffixes for future detailed searches.
CREATE TABLE IF NOT EXISTS dtworks.morph_segments (
    token_id            BIGINT NOT NULL REFERENCES dtworks.tokens(id) ON DELETE CASCADE,
    segment_index       SMALLINT NOT NULL CHECK (segment_index > 0),
    is_main             BOOLEAN NOT NULL DEFAULT false,
    morph_code          TEXT NOT NULL,
    language_code       CHAR(1) NOT NULL CHECK (language_code IN ('H','A')),
    pos_code            CHAR(1),
    subtype_code        CHAR(1),
    verb_stem_code      CHAR(1),
    verb_conjugation_code CHAR(1),
    person_code         CHAR(1),
    gender_code         CHAR(1),
    number_code         CHAR(1),
    state_code          CHAR(1),
    PRIMARY KEY (token_id, segment_index)
);

-- Indexes correspond directly to the current 050 UI.
CREATE INDEX IF NOT EXISTS idx_tokens_primary_strong
    ON dtworks.tokens (primary_strong);

CREATE INDEX IF NOT EXISTS idx_tokens_form_search
    ON dtworks.tokens (form_search);

CREATE INDEX IF NOT EXISTS idx_tokens_form_consonantal
    ON dtworks.tokens (form_consonantal);

CREATE INDEX IF NOT EXISTS idx_tokens_verb_morph
    ON dtworks.tokens (main_stem_code, main_conjugation_code)
    WHERE main_pos_code = 'V';

CREATE INDEX IF NOT EXISTS idx_tokens_lemma_verb_morph
    ON dtworks.tokens (primary_strong, main_stem_code, main_conjugation_code)
    WHERE main_pos_code = 'V';

CREATE INDEX IF NOT EXISTS idx_token_lemmas_strong
    ON dtworks.token_lemmas (strong_number, token_id);

CREATE INDEX IF NOT EXISTS idx_verses_book_reference
    ON dtworks.verses (book_id, chapter_wlc, verse_wlc);

-- Stable read surface for FastAPI. Create the base view only on a fresh
-- database. Later migrations append lexeme columns; replacing that expanded
-- production view here would try to drop columns and PostgreSQL rejects it.
DO $block$
BEGIN
    IF to_regclass('dtworks.search_tokens') IS NULL THEN
        EXECUTE $view$
            CREATE VIEW dtworks.search_tokens AS
            SELECT
                t.id AS token_id,
                b.osis_code AS book,
                b.english_name,
                b.japanese_name,
                b.tanakh_group,
                b.canonical_order,
                v.chapter_wlc,
                v.verse_wlc,
                v.osis_wlc,
                v.chapter_kjv,
                v.verse_kjv,
                v.osis_kjv,
                t.token_index,
                t.surface,
                t.form_search,
                t.form_consonantal,
                t.lemma_raw,
                t.primary_strong,
                t.lemma_display,
                t.morph_raw,
                t.language_code,
                t.main_pos_code,
                t.main_stem_code,
                t.main_conjugation_code,
                t.person_code,
                t.gender_code,
                t.number_code,
                t.state_code
            FROM dtworks.tokens t
            JOIN dtworks.verses v ON v.id = t.verse_id
            JOIN dtworks.books b ON b.id = v.book_id
        $view$;
    END IF;
END
$block$;

COMMIT;
